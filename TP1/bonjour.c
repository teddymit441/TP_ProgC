#include <stdio.h> // Inclusion de la bibliothèque standard pour gérer les entrées/sorties (comme l'affichage)

// C'est la fonction principale, le point de départ de tout programme en C
int main() {
    
    // printf permet d'afficher du texte à l'écran. 
    // Le '\n' à la fin sert à sauter une ligne (retour à la ligne).
    printf("Bonjour le Monde!\n");
    
    // On indique au système d'exploitation que le programme s'est terminé sans erreur (0)
    return 0;
}